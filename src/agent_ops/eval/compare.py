"""Model comparison: run one slice of the golden set under multiple brains and
produce a quality-vs-cost-vs-latency table.

`make compare`. The mock brain is instant and free (a deterministic baseline);
local Ollama is a real LLM (~30-60s/ticket, $0). If a provider isn't available
(e.g. Ollama not running), it's reported as unavailable and skipped.
"""

from __future__ import annotations

import os
from statistics import mean
from typing import Any

from rich.console import Console

from agent_ops.config import REPO_ROOT

_console = Console()

# A representative slice: a clean resolve, an auto-refund, an escalation,
# a duplicate-charge refund, a damaged-item, an identity gate, a cancellation,
# and a prompt-injection attempt.
SLICE = [
    "os-shipped",
    "rf-small-auto",
    "rf-over-threshold",
    "dc-small",
    "dmg-small",
    "addr-unverified",
    "cx-active",
    "inj-embedded-refund",
]


def _prep_storage() -> None:
    os.environ.setdefault("DB_PATH", "data/eval.db")
    os.environ.setdefault("TRACE_DIR", "data/eval_traces")


def _set_provider(provider: str) -> None:
    os.environ["LLM_PROVIDER"] = provider
    from agent_ops.config import get_settings

    get_settings.cache_clear()
    import agent_ops.backend.db as db

    db._engine = None
    db.init_db()
    from agent_ops.backend import kb
    from agent_ops.backend.kb_content import KB_ARTICLES

    if kb.get_collection().count() == 0:
        kb.index_articles(KB_ARTICLES)


def _agg(recs: list[dict[str, Any]]) -> dict[str, Any]:
    n = len(recs)
    return {
        "n": n,
        "success": sum(r["success"] for r in recs) / n,
        "safety": sum(r["safe"] for r in recs) / n,
        "tokens": mean((r["efficiency"]["tokens"] or 0) for r in recs),
        "cost": sum((r["efficiency"]["cost_usd"] or 0.0) for r in recs),
        "latency_ms": mean((r["efficiency"]["latency_ms"] or 0.0) for r in recs),
    }


def run_provider(provider: str, scenarios: list[dict[str, Any]]) -> dict[str, Any]:
    from agent_ops.eval.harness import run_one

    _set_provider(provider)
    _console.print(f"[cyan]running {len(scenarios)} scenarios on '{provider}'…[/]")
    recs = [run_one(s) for s in scenarios]
    return _agg(recs)


def render(results: dict[str, dict[str, Any]], scenarios: list[dict[str, Any]]) -> None:
    ids = ", ".join(s["id"] for s in scenarios)
    lines = [
        "# Model comparison",
        "",
        f"Same {len(scenarios)}-scenario slice, same agent loop / tools / guardrails, "
        "different reasoning brain. Generated by `make compare`.",
        "",
        f"Slice: `{ids}`",
        "",
        "| Reasoner | n | Task success | Action safety | Avg tokens | Total cost | Avg latency |",
        "|---|---|---|---|---|---|---|",
    ]
    for provider, a in results.items():
        if "error" in a:
            lines.append(f"| `{provider}` | — | _unavailable: {a['error']}_ | | | | |")
            continue
        lines.append(
            f"| `{provider}` | {a['n']} | {a['success']:.0%} | {a['safety']:.0%} | "
            f"{a['tokens']:.0f} | ${a['cost']:.4f} | {a['latency_ms'] / 1000:.1f}s |"
        )
    lines += [
        "",
        "> `mock` latency/cost are simulated (deterministic rules, $0, instant). Local Ollama "
        "runs a real model at $0 but real wall-clock latency. The point of the table is that "
        "**task success and — critically — action safety are measured the same way across brains**, "
        "so you can trade quality against cost/latency with eyes open.",
        "",
    ]
    out = REPO_ROOT / "docs" / "model-comparison.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    _console.print("\n".join(lines))
    _console.print(f"\n[green]wrote {out.relative_to(REPO_ROOT)}[/]")


def main(providers: tuple[str, ...] = ("mock", "ollama")) -> None:
    _prep_storage()
    from agent_ops.eval.harness import load_scenarios

    by_id = {s["id"]: s for s in load_scenarios()}
    scenarios = [by_id[i] for i in SLICE if i in by_id]

    results: dict[str, dict[str, Any]] = {}
    for provider in providers:
        try:
            results[provider] = run_provider(provider, scenarios)
        except Exception as e:  # e.g. Ollama not running
            results[provider] = {"error": str(e)[:120]}
            _console.print(f"[red]provider '{provider}' failed: {e}[/]")

    render(results, scenarios)


if __name__ == "__main__":
    main()
